/*
 * Generates the serialized default keymap record as a C source file.
 * Host tool (not part of the device image):
 *   cc -std=c99 -Os -I stock_extension -I tests \
 *      stock_extension/ck5200_keymap_engine.c \
 *      stock_extension/ck5200_keymap_serialize.c \
 *      stock_extension/ck5200_gen_record.c -o /tmp/gen_record
 *   /tmp/gen_record > stock_extension/ck5200_default_record.c
 */
#include <stdio.h>
#include <string.h>

#include "ck5200_keymap_engine.h"
#include "ck5200_keymap_serialize.h"

int main(void)
{
    ck_keymap_t map;
    /* Native actions must stay native. The host fixture remains a
     * keyboard-page reference, not the device's OEM policy table. */
    memset(&map, 0, sizeof(map));
    map.native_mask = CK_NATIVE_LAYERS;
    for (int layer = 0; layer < CK_LAYERS; layer++)
        for (int pos = 0; pos < CK_KEYS; pos++)
            map.action[layer][pos].kind = CK_ACTION_OEM;
    uint8_t buf[CK_KEYMAP_RECORD_MAX];
    size_t len = ck_keymap_serialize(&map, buf, sizeof(buf));
    if (len == 0) {
        fprintf(stderr, "serialization failed\n");
        return 1;
    }
    printf("/* Generated by ck5200_gen_record.c; do not edit. */\n");
    printf("#include <stdint.h>\n");
    printf("#include <stddef.h>\n");
    printf("const uint8_t ck_default_keymap_record[%zu] = {", len);
    for (size_t i = 0; i < len; i++)
        printf("%s0x%02x", i ? ", " : "", buf[i]);
    printf("};\n");
    printf("const unsigned int ck_default_keymap_record_len = %zu;\n", len);
    return 0;
}
